#!/usr/bin/env node
// Rebuilds lib/game-lab/manifest.arcade.ts from the files actually copied into
// assets/game-lab/practice-arcade. Run it after changing that tree, then commit
// the result. The asset route serves only the paths this file lists.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, relative } from 'node:path';

const ROOT = fileURLToPath(new URL('../../assets/game-lab/practice-arcade/', import.meta.url));
const OUT = fileURLToPath(new URL('../../lib/game-lab/manifest.arcade.ts', import.meta.url));

const SERVED = new Set(['.html', '.mjs', '.js', '.css', '.json', '.svg', '.png', '.txt', '.md']);

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
}

const files = [];
walk(ROOT, files);
const relativePaths = files
  .map((full) => relative(ROOT, full).split('\\').join('/'))
  .filter((rel) => SERVED.has(rel.slice(rel.lastIndexOf('.')).toLowerCase()))
  .sort();

const body = `/**
 * Generated by scripts/game-lab/generate-arcade-manifest.mjs. Do not edit by hand.
 * Every entry is an exact path under assets/game-lab/practice-arcade. The asset
 * route serves a request only when it matches one of these exactly.
 */
export const ARCADE_FILES: readonly string[] = [
${relativePaths.map((rel) => `  ${JSON.stringify(rel)},`).join('\n')}
];
`;
writeFileSync(OUT, body);
console.log(`wrote ${relativePaths.length} paths to lib/game-lab/manifest.arcade.ts`);
